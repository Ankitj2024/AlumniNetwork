import fs from 'node:fs';
import path from 'node:path';
import { Readable } from 'node:stream';
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client, type ServerSideEncryption } from '@aws-sdk/client-s3';
import { env } from '../config/env.js';

/**
 * Private file storage for verification documents.
 *
 * - `local`: files on the API server's disk (development, or a single server with a persistent,
 *   backed-up disk).
 * - `s3`: any S3-compatible bucket (AWS S3, Cloudflare R2, MinIO). The bucket stays private:
 *   files are streamed back through the API, which checks the viewer's role and writes an audit
 *   entry on every view, so no public or pre-signed URL ever exists.
 */
export interface FileStorage {
  readonly driver: 'local' | 's3';
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  /** The file's contents, or null if it doesn't exist. */
  get(key: string): Promise<Readable | null>;
  remove(key: string): Promise<void>;
}

/** Keys are generated by the server (e.g. "verification/<uuid>.pdf"); this rejects anything else. */
export function assertSafeKey(key: string) {
  if (!/^[a-zA-Z0-9][a-zA-Z0-9/_.-]{0,200}$/.test(key) || key.includes('..') || key.includes('//')) throw new Error('Invalid storage key');
}

export class LocalStorage implements FileStorage {
  readonly driver = 'local' as const;
  constructor(private readonly dir: string) {}

  private resolve(key: string) {
    assertSafeKey(key);
    const root = path.resolve(this.dir);
    const full = path.resolve(root, key);
    if (!full.startsWith(root + path.sep)) throw new Error('Invalid storage key');
    return full;
  }
  async put(key: string, body: Buffer) {
    const file = this.resolve(key);
    await fs.promises.mkdir(path.dirname(file), { recursive: true });
    await fs.promises.writeFile(file, body, { flag: 'wx' }); // never overwrite
  }
  async get(key: string) {
    const file = this.resolve(key);
    return fs.existsSync(file) ? fs.createReadStream(file) : null;
  }
  async remove(key: string) {
    await fs.promises.rm(this.resolve(key), { force: true });
  }
}

/** The subset of the AWS SDK client used here (lets tests pass a fake). */
export type S3Like = { send(command: unknown): Promise<any> };

export class S3Storage implements FileStorage {
  readonly driver = 's3' as const;
  constructor(
    private readonly client: S3Like,
    private readonly bucket: string,
    private readonly sse = '',
  ) {}

  async put(key: string, body: Buffer, contentType: string) {
    assertSafeKey(key);
    await this.client.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: key,
        Body: body,
        ContentType: contentType,
        ...(this.sse ? { ServerSideEncryption: this.sse as ServerSideEncryption } : {}),
      }),
    );
  }
  async get(key: string) {
    assertSafeKey(key);
    try {
      const out = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
      const body = out.Body;
      if (!body) return null;
      return body instanceof Readable ? body : Readable.from(Buffer.from(await body.transformToByteArray()));
    } catch (e: any) {
      if (e?.name === 'NoSuchKey' || e?.$metadata?.httpStatusCode === 404) return null;
      throw e;
    }
  }
  async remove(key: string) {
    assertSafeKey(key);
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

let instance: FileStorage | null = null;

export function storage(): FileStorage {
  if (instance) return instance;
  if (env.storageDriver === 's3') {
    const { bucket, region, endpoint, accessKeyId, secretAccessKey, forcePathStyle, sse } = env.s3;
    if (!bucket) throw new Error('STORAGE_DRIVER=s3 needs S3_BUCKET');
    const client = new S3Client({
      region,
      ...(endpoint ? { endpoint } : {}),
      forcePathStyle,
      ...(accessKeyId && secretAccessKey ? { credentials: { accessKeyId, secretAccessKey } } : {}), // else: the platform's IAM role
    });
    instance = new S3Storage(client, bucket, sse);
  } else {
    instance = new LocalStorage(env.uploadDir);
  }
  return instance;
}

/** Tests swap in their own storage. */
export function setStorage(s: FileStorage | null) {
  instance = s;
}
