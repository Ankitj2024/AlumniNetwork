/**
 * Builds the land mask for the hero globe (src/components/three/landDots.ts).
 *
 * The globe is drawn as rows of evenly spaced dots. Each row sits at a fixed latitude and has
 * as many dots as fit around that circle, so spacing stays even from the equator to the poles.
 * For every dot we test whether it falls on land (Natural Earth 1:110m, public domain, via the
 * `world-atlas` package) and pack the answers into a bit mask: ~4 KB instead of a texture.
 *
 *   node apps/web/scripts/generate-land-dots.mjs
 *
 * The client rebuilds dot positions from LAND_ROWS and the mask (see `landDotPositions` in
 * src/components/three/globeData.ts), using the same longitude formula as below.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoBounds, geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));

const LAT_MAX = 78; // northern edge of Greenland / Svalbard
const LAT_MIN = -56; // Cape Horn; Antarctica is left out on purpose (reads as noise on a tilted globe)
const STEP = 1.1; // degrees between rows and between dots along a row

const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);
// Split into polygons with bounding boxes so each test only checks nearby shapes.
const polys = land.features
  .flatMap((f) => (f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates.map((c) => ({ type: 'Polygon', coordinates: c })) : [f.geometry]))
  .map((g) => ({ g, b: geoBounds(g) }));

const inBox = ([lng, lat], [[w, s], [e, n]]) => lat >= s && lat <= n && (w <= e ? lng >= w && lng <= e : lng >= w || lng <= e);
const isLand = (p) => polys.some(({ g, b }) => inBox(p, b) && geoContains(g, p));

const rows = Math.floor((LAT_MAX - LAT_MIN) / STEP) + 1;
const bits = [];
const rowCounts = [];
let landCount = 0;
for (let r = 0; r < rows; r++) {
  const lat = LAT_MAX - r * STEP;
  const n = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / STEP));
  rowCounts.push(n);
  for (let k = 0; k < n; k++) {
    const lng = -180 + ((k + 0.5) * 360) / n;
    const on = isLand([lng, lat]);
    bits.push(on ? 1 : 0);
    if (on) landCount++;
  }
}

const bytes = new Uint8Array(Math.ceil(bits.length / 8));
bits.forEach((b, i) => {
  if (b) bytes[i >> 3] |= 1 << (i & 7);
});
const mask = Buffer.from(bytes).toString('base64');

const out = resolve(here, '../src/components/three/landDots.ts');
writeFileSync(
  out,
  `// Generated by scripts/generate-land-dots.mjs from Natural Earth 1:110m land (public domain,
// via the world-atlas package). Do not edit by hand: re-run the script instead.
// ${bits.length} grid dots, ${landCount} on land.
export const LAND_GRID = { latMax: ${LAT_MAX}, step: ${STEP}, rows: ${rows}, total: ${bits.length} } as const;
// Dots per row, north to south (written out so the client never re-derives them with rounding drift).
export const LAND_ROWS: readonly number[] = [${rowCounts.join(',')}];
export const LAND_MASK = '${mask}';
`,
);
console.log(`wrote ${out}: ${rows} rows, ${bits.length} dots, ${landCount} land, ${mask.length} chars`);
